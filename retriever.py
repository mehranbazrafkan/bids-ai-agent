MIN_BEST_SCORE = 3.0

# Issue-aware retrieval ----------------------------------------------------
# When the planner passes a serialized issue object (compact_json), the
# retriever must NOT treat the flat text as one equally-weighted bag of
# words. These keys are recognized while parsing the serialization so that
# the rule_id / field / severity become structured, highly-weighted query
# components instead of ordinary tokens.
_KNOWN_ISSUE_KEYS = frozenset({
    "severity", "rule_id", "message", "field", "path",
    "suffix", "datatype", "issues", "sidecar_fields",
    "line", "lines", "fix_label", "fix_action", "mirrored",
})

# Issue keys whose values carry no retrieval signal (they only exist in the
# error object as structural bookkeeping) and would otherwise pollute the
# query with coincidental tokens such as "line" / "lines".
_NONSEMANTIC_ISSUE_KEYS = frozenset({
    "line", "lines", "fix_label", "fix_action", "mirrored", "sidecar_fields",
})


def _parse_query(query: str) -> dict:
    """
    Attempt to parse a serialized issue object out of a query string.

    The BIDS planner currently passes ``"{user_input} {compact_json(issue)}"``
    to ``Retriever.retrieve()``. ``compact_json`` renders the issue as
    ``severity:err rule_id:JSON_SCHEMA_VALIDATION_ERROR message:... field:...``.
    Recognizing this structure lets the retriever weight the *role* of each
    piece of the issue (rule id, field name, message, severity) instead of
    scoring every word identically.

    Returns a dict of the recognized semantic components (e.g.
    ``{"rule_id": "...", "field": "...", "message_text": "...",
    "severity": "err", "general_text": "Explain this to me."}``), or an
    empty dict when the query is a plain natural-language string (no issue
    serialization detected) - in which case the caller falls back to
    standard full-text scoring.
    """
    if not query or not query.strip():
        return {}

    keys_alt = "|".join(
        re.escape(k) for k in sorted(_KNOWN_ISSUE_KEYS, key=len, reverse=True)
    )
    field_re = re.compile(rf"(?:^|\s)({keys_alt}):")
    matches = list(field_re.finditer(query))
    if len(matches) < 2:
        return {}

    root_fields: Dict[str, str] = {}
    for i, m in enumerate(matches):
        root_fields[m.group(1)] = query[m.end(): matches[i + 1].start() if i + 1 < len(matches) else len(query)].strip()

    # Extract the semantic values; a later match with the same key (e.g. the
    # nested issue inside "issues:[...]") legitimately overwrites the outer
    # one, so the innermost issue wins.
    result: Dict[str, str] = {}
    for key in ("rule_id", "field", "severity", "message", "path",
                "suffix", "datatype"):
        if key in _NONSEMANTIC_ISSUE_KEYS:
            continue
        value = _clean_issue_value(root_fields.get(key))
        if value:
            result["message_text" if key == "message" else key] = value

    # nested issues (sample_issue_003 style): lift the inner issue's fields
    nested = root_fields.get("issues", "")
    if nested and not result.get("rule_id"):
        nested_rid = re.search(r"\brule_id:(\S+)", nested)
        nested_ft = re.search(r"\bfield:(\S+)", nested)
        if nested_rid:
            result["rule_id"] = _clean_issue_value(nested_rid.group(1).rstrip("}"))
        if nested_ft:
            result["field"] = _clean_issue_value(nested_ft.group(1).rstrip("}"))

    general_end = matches[0].start() if matches else 0
    general_text = query[:general_end].strip()
    if general_text:
        result["general_text"] = general_text

    return result


def _clean_issue_value(value: Any) -> str:
    """Strip/skip issue values that carry no retrieval signal.

    Sentence-worthy values must survive untouched (they are scored), while
    JSON bookkeeping placeholders such as ``"null"`` or ``"none"`` are
    dropped so they never leak tokens like 'null' into the query.
    """
    if value is None:
        return ""
    text = str(value).strip()
    if not text or text.lower() in ("null", "none"):
        return ""
    return text


def _issue_structured(issue: dict) -> dict:
    """
    Build the structured retrieval components directly from an issue dict.

    Mirrors the output shape of ``_parse_query`` (keys ``rule_id``,
    ``field``, ``severity``, ``message_text``, ``path``, ``suffix``,
    ``datatype``) but without the lossy string round-trip, so callers that
    already hold the structured issue (e.g. ``Retriever.retrieve_issue``)
    can pass exact values instead of re-serializing and re-parsing them.
    """
    if not isinstance(issue, dict) or not issue:
        return {}

    combined: Dict[str, Any] = dict(issue)
    inner = issue.get("issues")
    if isinstance(inner, list) and inner:
        inner_issue = inner[0]
        if isinstance(inner_issue, dict):
            for key, value in inner_issue.items():
                combined.setdefault(key, value)

    result: Dict[str, str] = {}
    for key in ("rule_id", "field", "severity", "message", "path",
                "suffix", "datatype"):
        value = _clean_issue_value(combined.get(key))
        if value:
            result["message_text" if key == "message" else key] = value
    return result


