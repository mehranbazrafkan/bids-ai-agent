class KnowledgeRecord:
    """
    One record from knowledge.jsonl.

    Maps the real top-level fields of the generated knowledge base:
        id, knowledge_type, title, summary, retrieval_text, scope,
        source, raw_content, bids_version, schema_version, and the
        optional rule fields: requirements, conditions, allowed_values,
        severity, expression, unit.
    """

    __slots__ = (
        "id", "knowledge_type", "title", "summary", "retrieval_text",
        "source", "scope", "raw_content", "bids_version", "schema_version",
        "requirements", "conditions", "allowed_values",
        "severity", "expression", "unit",
    )

    def __init__(self, data: Dict[str, Any]) -> None:
        self.id: str = str(data.get("id", "") or "")
        self.knowledge_type: str = str(data.get("knowledge_type", "unknown"))
        self.title: str = str(data.get("title", "") or "")
        self.summary: str = str(data.get("summary", "") or "")
        self.retrieval_text: str = str(data.get("retrieval_text", "") or "")
        self.source: Dict[str, Any] = data.get("source") or {}
        self.scope: Dict[str, Any] = data.get("scope") or {}
        self.raw_content: Any = data.get("raw_content")
        self.bids_version: str = str(data.get("bids_version", "") or "")
        self.schema_version: str = str(data.get("schema_version", "") or "")
        self.requirements: Any = data.get("requirements")
        self.conditions: Any = data.get("conditions")
        self.allowed_values: Any = data.get("allowed_values")
        self.severity: Any = data.get("severity")
        self.expression: Any = data.get("expression")
        self.unit: Any = data.get("unit")

    # -- searchable representation ------------------------------------

    def build_search_blocks(self) -> List[Tuple[str, str, float]]:
        """
        Build the searchable representation of this record as a list of
        ``(label, text, weight)`` tuples.

        Weights reflect how discriminating each field is:
        * the rules/errors ``code`` (``requirements.code``) and the record
          id are the most specific identifiers;
        * free-text descriptions are the least specific.
        """
        blocks: List[Tuple[str, str, float]] = []

        def add(label: str, text: Any, weight: float) -> None:
            text = self._normalize(text)
            if text:
                blocks.append((label, text, weight))

        add("id", self.id, 4.0)
        add("title", self.title, 3.0)
        add("scope", self._flatten(self.scope), 3.0)
        add("requirements", self._flatten(self.requirements), 2.5)
        # The rules/errors code (e.g. "JSON_SCHEMA_VALIDATION_ERROR",
        # "WRONG_NEW_LINE") is the single most identity-bearing check value.
        if isinstance(self.requirements, dict) and self.requirements.get("code"):
            add("code", str(self.requirements["code"]), 5.0)
        add("allowed_values", self._flatten(self.allowed_values), 2.0)
        add("conditions", self._flatten(self.conditions), 2.0)
        add("summary", self.summary, 1.5)
        add("retrieval", self.retrieval_text, 1.5)
        add("expression", self.expression, 1.5)
        add("severity", self.severity, 1.0)
        add("unit", self.unit, 1.0)
        add("raw_content", json.dumps(self.raw_content, ensure_ascii=False), 0.8)

        return blocks

    def identity_text(self) -> str:
        """Compact text of the most identity-bearing fields (id/title/scope)."""
        return self._normalize(" ".join([
            self.id,
            self.title,
            self._flatten(self.scope),
        ]))

    # -- helpers --------------------------------------------------------

    @staticmethod
    def _normalize(text: Any) -> str:
        """
        Normalize text for matching, lowercase and treat '_' as a word
        separator (BIDS ids use it). CamelCase is split first so that an
        identifier such as ``ReferencesAndLinks`` becomes the word phrase
        ``references and links`` and can be matched against tokens like
        ``references`` / ``links`` that appear separately in KB records.
        """
        text = str(text or "")
        text = re.sub(r"([a-z])([A-Z])", r"\1 \2", text)
        text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", text)
        return re.sub(r"[^a-z0-9 ]", " ", text.lower()).strip()

    @classmethod
    def _flatten(cls, value: Any) -> str:
        """Serialize arbitrary JSON values into a flat searchable string."""
        if value is None:
            return ""
        if isinstance(value, str):
            return value
        if isinstance(value, dict):
            return " ".join(
                f"{k}: {cls._flatten(v)}" for k, v in value.items()
            )
        if isinstance(value, (list, tuple)):
            return " ".join(cls._flatten(v) for v in value)
        return str(value)


